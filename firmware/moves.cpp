uint16_t signatureMoveForSpecies(int16_t dex) {
  return dex >= 1 && dex <= 151 ? SIGNATURE_MOVE[dex] : MOVE_NONE;
}

uint8_t commonMoveCountForSpecies(int16_t dex) {
  return dex >= 1 && dex <= 151 ? COMMON_COUNT[dex] : 0;
}

uint16_t commonMoveForSpecies(int16_t dex, uint8_t index) {
  uint8_t count = commonMoveCountForSpecies(dex);
  if (index >= count) return MOVE_NONE;
  return COMMON_MOVES[COMMON_OFFSET[dex] + index];
}

uint16_t chooseCommonMoveForSpecies(int16_t dex, uint32_t seed) {
  uint8_t count = commonMoveCountForSpecies(dex);
  return count ? commonMoveForSpecies(dex, (uint8_t)(seed % count)) : signatureMoveForSpecies(dex);
}
